/**
 * Unit tests for BlockingScheduleRepositoryImpl. Uses FakeBlockingScheduleDao
 * + FakeClock + FixedZoneIdProvider so the predicate/business logic is
 * exercised without a real Room instance or system zone. Covers happy paths
 * (create, observe, purge) and border cases (validation, update/delete
 * during active window).
 * Covers: ULT-24, ULT-25
 */
package com.ultimatefocus.app.data.repository

import com.ultimatefocus.app.data.local.dao.FakeBlockingScheduleDao
import com.ultimatefocus.app.domain.model.DayOfWeekMask
import com.ultimatefocus.app.domain.repository.BlockingScheduleDraft
import com.ultimatefocus.app.domain.repository.InvalidBlockingScheduleException
import com.ultimatefocus.app.domain.repository.ScheduleCurrentlyActiveException
import com.ultimatefocus.app.domain.service.FakeClock
import com.ultimatefocus.app.domain.service.FixedZoneIdProvider
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import java.time.DayOfWeek
import java.time.LocalTime
import java.time.ZoneId
import java.time.ZonedDateTime

class BlockingScheduleRepositoryImplTest {

    private lateinit var dao: FakeBlockingScheduleDao
    private lateinit var clock: FakeClock
    private lateinit var repo: BlockingScheduleRepositoryImpl

    private val zone: ZoneId = ZoneId.of("Europe/Warsaw")
    private val zoneProvider = FixedZoneIdProvider(zone)

    private fun wedAt(hour: Int, minute: Int): Long =
        ZonedDateTime.of(2026, 4, 22, hour, minute, 0, 0, zone).toInstant().toEpochMilli()

    private fun draft(
        name: String = "Work Focus",
        start: Int = 9 * 60,
        end: Int = 17 * 60,
        days: Set<DayOfWeek> = setOf(DayOfWeek.WEDNESDAY),
        packages: Set<String> = setOf("com.test"),
    ): BlockingScheduleDraft = BlockingScheduleDraft(
        name = name,
        startMinuteOfDay = start,
        endMinuteOfDay = end,
        daysOfWeekMask = DayOfWeekMask.encode(days),
        packageNames = packages,
    )

    @Before
    fun setUp() {
        dao = FakeBlockingScheduleDao()
        // 2026-04-22 08:00 local — Wednesday, before the 9-5 window.
        clock = FakeClock(current = wedAt(8, 0))
        repo = BlockingScheduleRepositoryImpl(dao, clock, zoneProvider)
    }

    // ── Happy paths ─────────────────────────────────────────────────────────

    @Test
    fun create_assignsAutoGeneratedId() = runTest {
        val id = repo.create(draft())
        assertTrue(id > 0L)
        assertNotNull(repo.getById(id))
        assertEquals(1, dao.scheduleSize)
        assertEquals(1, dao.junctionSize)
    }

    @Test
    fun create_persistsAssignedApps() = runTest {
        val id = repo.create(draft(packages = setOf("com.a", "com.b")))
        val schedule = repo.getById(id)!!
        assertEquals(setOf("com.a", "com.b"), schedule.packageNames)
    }

    @Test
    fun observeAll_emitsCreatedSchedule() = runTest {
        repo.create(draft(name = "First"))
        val all = repo.observeAll().first()
        assertEquals(1, all.size)
        assertEquals("First", all[0].name)
    }

    @Test
    fun observeActivePackageNames_emitsWhenWithinWindow() = runTest {
        repo.create(draft(packages = setOf("com.a")))
        clock.current = wedAt(12, 0) // mid-window
        val active = repo.observeActivePackageNames().first()
        assertEquals(setOf("com.a"), active)
    }

    @Test
    fun observeActivePackageNames_emitsEmptyOutsideWindow() = runTest {
        repo.create(draft(packages = setOf("com.a")))
        // clock is 08:00 in setUp() — before the 09:00 window start.
        val active = repo.observeActivePackageNames().first()
        assertTrue(active.isEmpty())
    }

    @Test
    fun observeActiveWindowEndByPackage_emitsWindowEndPerPackage() = runTest {
        repo.create(draft(packages = setOf("com.a", "com.b")))
        clock.current = wedAt(12, 0)
        val map = repo.observeActiveWindowEndByPackage().first()
        assertEquals(wedAt(17, 0), map["com.a"])
        assertEquals(wedAt(17, 0), map["com.b"])
    }

    @Test
    fun activePackageNamesNow_returnsSnapshot() = runTest {
        repo.create(draft(packages = setOf("com.a")))
        clock.current = wedAt(12, 0)
        assertEquals(setOf("com.a"), repo.activePackageNamesNow())
    }

    @Test
    fun activeScheduleFor_returnsActiveSchedule() = runTest {
        val id = repo.create(draft(name = "Work Focus", packages = setOf("com.a")))
        clock.current = wedAt(12, 0)
        val active = repo.activeScheduleFor("com.a")
        assertNotNull(active)
        assertEquals(id, active!!.id)
        assertEquals("Work Focus", active.name)
        assertEquals(wedAt(17, 0), active.windowEndEpochMs)
    }

    @Test
    fun purgePackage_removesAssignmentsAcrossSchedules() = runTest {
        val id1 = repo.create(draft(name = "S1", packages = setOf("com.a", "com.b")))
        val id2 = repo.create(draft(name = "S2", packages = setOf("com.a")))
        repo.purgePackage("com.a")
        val s1 = repo.getById(id1)!!
        val s2 = repo.getById(id2)!!
        assertEquals(setOf("com.b"), s1.packageNames)
        assertTrue(s2.packageNames.isEmpty())
    }

    @Test
    fun delete_removesScheduleAndJunctionRowsWhenInactive() = runTest {
        val id = repo.create(draft())
        // Setup clock is before window — schedule not active.
        repo.delete(id)
        assertNull(repo.getById(id))
        assertEquals(0, dao.scheduleSize)
        assertEquals(0, dao.junctionSize)
    }

    @Test
    fun update_changesNameWhenInactive() = runTest {
        val id = repo.create(draft(name = "Before"))
        repo.update(id, draft(name = "After"))
        assertEquals("After", repo.getById(id)!!.name)
    }

    // ── Border cases ────────────────────────────────────────────────────────

    @Test(expected = InvalidBlockingScheduleException::class)
    fun create_rejectsBlankName() = runTest {
        repo.create(draft(name = "  "))
    }

    @Test(expected = InvalidBlockingScheduleException::class)
    fun create_rejectsEmptyDays() = runTest {
        repo.create(draft(days = emptySet()))
    }

    @Test(expected = InvalidBlockingScheduleException::class)
    fun create_rejectsEmptyPackages() = runTest {
        repo.create(draft(packages = emptySet()))
    }

    @Test(expected = InvalidBlockingScheduleException::class)
    fun create_rejectsStartEqualsEnd() = runTest {
        repo.create(draft(start = 600, end = 600))
    }

    @Test(expected = InvalidBlockingScheduleException::class)
    fun create_rejectsTimeOutsideRange() = runTest {
        repo.create(draft(start = -1, end = 600))
    }

    @Test(expected = ScheduleCurrentlyActiveException::class)
    fun update_throwsWhenScheduleIsCurrentlyActive() = runTest {
        val id = repo.create(draft())
        clock.current = wedAt(12, 0) // mid-window
        repo.update(id, draft(name = "New name"))
    }

    @Test(expected = ScheduleCurrentlyActiveException::class)
    fun delete_throwsWhenScheduleIsCurrentlyActive() = runTest {
        val id = repo.create(draft())
        clock.current = wedAt(12, 0)
        repo.delete(id)
    }

    @Test
    fun update_succeedsAfterWindowEnds() = runTest {
        val id = repo.create(draft())
        clock.current = wedAt(17, 0) // exactly at end — exclusive, so inactive.
        repo.update(id, draft(name = "After"))
        assertEquals("After", repo.getById(id)!!.name)
    }

    @Test
    fun delete_succeedsForUnknownId_isNoOp() = runTest {
        repo.delete(99L) // must not throw
        assertEquals(0, dao.scheduleSize)
    }
}
